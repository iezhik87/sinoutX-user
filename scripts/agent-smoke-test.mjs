// Нормализуем числа: «1 417», «1 417», «1,417», «1417» → «1417». Чтобы искать
// ожидаемое значение в свободном тексте ответа независимо от форматирования.
const digits = (s) => String(s).replace(/(\d)[\s ,](?=\d)/g, '$1')
const has = (text, ...nums) => nums.every((n) => digits(text).includes(digits(n)))
const hasNone = (text, ...nums) => nums.every((n) => !digits(text).includes(digits(n)))
const lower = (t) => t.toLowerCase()

// Один запрос к агенту. messages — полная история, возвращает текст ответа.
async function ask(messages) {
  const res = await fetch(`${BASE_URL}/api/v1/ai/chat`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'x-api-key': API_KEY },
    body: JSON.stringify({ messages, context: WORKSPACE_ID ? { workspaceId: WORKSPACE_ID } : {} }),
  })
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${(await res.text()).slice(0, 200)}`)
  let text = '', err = ''
  const reader = res.body.getReader()
  const dec = new TextDecoder()
  let buf = ''
  for (;;) {
    const { done, value } = await reader.read()
    if (done) break
    buf += dec.decode(value, { stream: true })
    const lines = buf.split('\n'); buf = lines.pop() ?? ''
    for (const line of lines) {
      const s = line.replace(/^data:\s?/, '').trim()
      if (!s) continue
      try {
        const p = JSON.parse(s)
        if (p.type === 'text' && p.text) text += p.text
        else if (p.type === 'error' && p.text) err += p.text
      } catch { /* ignore non-json keepalive */ }
    }
  }
  if (!text.trim() && err) throw new Error(`Ошибка провайдера: ${err}`)
  return text.trim()
}

// Прогнать многоходовый сценарий: массив реплик пользователя. Проверяется ПОСЛЕДНИЙ ответ.
async function runTurns(userTurns, check) {
  const messages = []
  let last = ''
  for (const turn of userTurns) {
    messages.push({ role: 'user', content: turn })
    last = await ask(messages)
    messages.push({ role: 'assistant', content: last })
  }
  return { ok: check(last, messages), reply: last }
}

