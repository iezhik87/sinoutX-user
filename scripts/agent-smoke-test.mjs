// ── Прогон ───────────────────────────────────────────────────────────────────
const run = async () => {
  console.log(`Агент: ${BASE_URL}  ws=${WORKSPACE_ID || '(нет)'}\n`)
  let pass = 0, fail = 0, errs = 0
  for (let i = 0; i < TESTS.length; i++) {
    if (ONLY !== null && ONLY !== i + 1) continue
    const test = TESTS[i]
    process.stdout.write(`${String(i + 1).padStart(2)}. ${test.name} … `)
    try {
      const { ok, reply } = await runTurns(test.turns, test.check)
      console.log(ok ? '✅' : '❌ НАДО ГЛЯНУТЬ')
      if (!ok) { console.log('   ── ответ агента ──\n' + reply.split('\n').map((l) => '   ' + l).join('\n') + '\n'); fail++ } else pass++
    } catch (e) {
      console.log('💥 ' + e.message); errs++
    }
  }
  console.log(`\nИтог: ${pass} ✅ / ${fail} ❌ / ${errs} 💥`)
  console.log('❌ = ответ не прошёл автопроверку — прочитай его глазами: возможно, реальная ошибка агента, а возможно, он ответил верно, но иначе, чем ждал скрипт.')
  // Ненулевой выход при провале/ошибке — чтобы гонять как гейт после деплоя
  // (docker compose up --build backend && node scripts/agent-smoke-test.mjs || «откат/разбор»).
  if (fail > 0 || errs > 0) process.exit(1)
}
run().catch((e) => { console.error(e); process.exit(1) })
