export interface BuiltinPageTemplate {
  id: string
  category: 'business' | 'reports' | 'planning' | 'hr' | 'technical' | 'education' | 'personal'
  icon: string
  ru: { name: string; desc: string }
  en: { name: string; desc: string }
  contentEn?: Record<string, unknown>
  contentBe?: Record<string, unknown>
  content: Record<string, unknown>  // Russian content (default fallback)
}

function doc(...nodes: unknown[]): Record<string, unknown> {
  return { type: 'doc', content: nodes }
}
function h(level: number, text: string) {
  return { type: 'heading', attrs: { level }, content: [{ type: 'text', text }] }
}
function p(text = '') {
  return text
    ? { type: 'paragraph', content: [{ type: 'text', text }] }
    : { type: 'paragraph' }
}
function ul(...items: string[]) {
  return {
    type: 'bulletList',
    content: items.map((t) => ({
      type: 'listItem',
      content: [{ type: 'paragraph', content: [{ type: 'text', text: t }] }],
    })),
  }
}
function ol(...items: string[]) {
  return {
    type: 'orderedList',
    content: items.map((t) => ({
      type: 'listItem',
      content: [{ type: 'paragraph', content: [{ type: 'text', text: t }] }],
    })),
  }
}
function hr() { return { type: 'horizontalRule' } }
function table(headers: string[], rows: string[][]) {
  return {
    type: 'table',
    content: [
      {
        type: 'tableRow',
        content: headers.map((h) => ({
          type: 'tableHeader',
          attrs: { colspan: 1, rowspan: 1 },
          content: [{ type: 'paragraph', content: [{ type: 'text', text: h, marks: [{ type: 'bold' }] }] }],
        })),
      },
      ...rows.map((row) => ({
        type: 'tableRow',
        content: row.map((cell) => ({
          type: 'tableCell',
          attrs: { colspan: 1, rowspan: 1 },
          content: [{ type: 'paragraph', content: cell ? [{ type: 'text', text: cell }] : [] }],
        })),
      })),
    ],
  }
}

